-- =============================================
-- PostgreSQL initialization script
-- File: init_users.sql
-- Purpose: initial setup of database, roles, privileges, and sample table
-- =============================================

-- Create application database when missing. This script is intended for psql.
SELECT 'CREATE DATABASE appdb ENCODING ''UTF8'' TEMPLATE template0'
WHERE NOT EXISTS (
  SELECT FROM pg_database WHERE datname = 'appdb'
)\gexec

\connect appdb

DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'app_admin') THEN
    CREATE ROLE app_admin LOGIN PASSWORD 'S3cur3P@ss!' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;

  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'app_reader') THEN
    CREATE ROLE app_reader LOGIN PASSWORD 'Read0nly!' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END
$$;

ALTER ROLE app_admin NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
ALTER ROLE app_reader NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;

REVOKE ALL ON DATABASE appdb FROM PUBLIC;
REVOKE ALL ON DATABASE postgres FROM PUBLIC;
REVOKE ALL ON DATABASE template1 FROM PUBLIC;

GRANT CONNECT, TEMPORARY ON DATABASE appdb TO app_admin;
GRANT CONNECT ON DATABASE appdb TO app_reader;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO app_admin;
GRANT USAGE ON SCHEMA public TO app_reader;

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO public.users (email)
VALUES ('first.user@example.com')
ON CONFLICT (email) DO NOTHING;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO app_admin;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO app_admin;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO app_reader;

ALTER DEFAULT PRIVILEGES FOR ROLE app_admin IN SCHEMA public
  GRANT SELECT ON TABLES TO app_reader;

SELECT 'PostgreSQL initialization completed.' AS status;
